const LUZDOSOL_LOCALE_MAP = { fr: 'fr-FR', en: 'en-GB', es: 'es-ES', pt: 'pt-PT' };
window.LUZDOSOL_LOCALE_MAP = LUZDOSOL_LOCALE_MAP;
window.LUZDOSOL_LANG = 'fr';

function luzdosolT(key) {
  const dict = LUZDOSOL_I18N[window.LUZDOSOL_LANG] || LUZDOSOL_I18N.fr;
  return (key in dict) ? dict[key] : LUZDOSOL_I18N.fr[key];
}
window.luzdosolT = luzdosolT;

function applyLuzdosolLang(lang) {
  if (!LUZDOSOL_I18N[lang]) return;
  window.LUZDOSOL_LANG = lang;
  localStorage.setItem('luzdosol_lang', lang);
  document.documentElement.lang = lang;

  // Ne touche au <title>/meta description que sur l'accueil : ce sont les seules
  // clés traduites (meta_title/meta_description) — sur les autres pages, les
  // écraser remplacerait leur titre spécifique (ex. "Guide du séjour") par celui
  // de l'accueil à chaque changement de langue.
  const path = location.pathname.replace(/\/+$/, '');
  const isHome = path === '' || path.endsWith('/index.html') || !/\.html$/i.test(path);
  if (isHome) {
    document.title = luzdosolT('meta_title');
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.setAttribute('content', luzdosolT('meta_description'));
  }

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = luzdosolT(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = luzdosolT(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.setAttribute('placeholder', luzdosolT(el.dataset.i18nPh));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', luzdosolT(el.dataset.i18nAria));
  });

  const stayLabel = document.getElementById('stay-label');
  if (stayLabel && !stayLabel.dataset.set) stayLabel.textContent = luzdosolT('stay_default');

  document.querySelectorAll('.lang-switch [data-lang]').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  window.dispatchEvent(new CustomEvent('luzdosol-lang-change', { detail: { lang } }));
}
window.applyLuzdosolLang = applyLuzdosolLang;

document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('luzdosol_lang');
  const browserLang = (navigator.language || 'fr').slice(0, 2);
  const initial = saved || (LUZDOSOL_I18N[browserLang] ? browserLang : 'fr');
  applyLuzdosolLang(initial);
  document.querySelectorAll('.lang-switch [data-lang]').forEach(btn => {
    btn.addEventListener('click', () => applyLuzdosolLang(btn.dataset.lang));
  });
});
